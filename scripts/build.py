#!/usr/bin/env python3
"""Build step for the Adela Privé site.

Runs automatically on GitHub (see .github/workflows/pages.yml) every time
the admin page saves a change. You can also run it locally:

    python scripts/build.py

It does two things:
  1. Reads every piece in content/products/*.json (the files the admin page
     edits) and writes assets/js/products.js, which the site loads.
  2. Makes a 500px "-sm" copy of each photo in assets/uploads/ for the grid,
     so phones load small images.
"""
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "products"
UPLOADS = ROOT / "assets" / "uploads"
OUT = ROOT / "assets" / "js" / "products.js"


def local(src: str) -> str:
    """'/assets/uploads/x.webp' -> 'assets/uploads/x.webp?v=1a2b3c4d' (works under any sub-path).

    The ?v= part is a fingerprint of the photo, so when a photo is replaced under the
    same name, browsers fetch the new one instead of showing a cached copy."""
    path = re.sub(r"^/+", "", (src or "").strip()).split("?")[0]
    f = ROOT / path
    if f.is_file():
        return path + "?v=" + hashlib.md5(f.read_bytes()).hexdigest()[:8]
    return path


def pair(en: str, bg: str) -> dict:
    en, bg = (en or "").strip(), (bg or "").strip()
    return {"en": en, "bg": bg or en}


def load_products() -> list:
    items = []
    for f in sorted(CONTENT.glob("*.json")):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception as e:  # a broken file should not take the whole site down
            print(f"skipping {f.name}: {e}", file=sys.stderr)
            continue
        if not (d.get("name_en") or "").strip():
            continue
        dims = (d.get("dimensions") or "").strip()
        images = d.get("images") or []
        if isinstance(images, str):
            images = [images]
        items.append({
            "id": f.stem,
            "ref": (d.get("ref") or "").strip(),
            "order": d.get("order") if isinstance(d.get("order"), (int, float)) else 1000,
            "category": d.get("category") or "purses",
            "status": d.get("status") or "available",
            "price": (d.get("price") or "").strip(),
            "featured": bool(d.get("featured")),
            "hero": bool(d.get("hero")),
            "images": [local(s) for s in images if s],
            "name": pair(d.get("name_en"), d.get("name_bg")),
            "description": pair(d.get("description_en"), d.get("description_bg")),
            "details": {
                "material": pair(d.get("material_en"), d.get("material_bg")),
                "dimensions": {"en": dims, "bg": dims.replace("cm", "см")},
                "colour": pair(d.get("colour_en"), d.get("colour_bg")),
            },
        })
    items.sort(key=lambda p: (p["order"], p["id"]))
    for p in items:
        del p["order"]
    return items


def write_products(items: list) -> None:
    body = json.dumps(items, ensure_ascii=False, indent=2)
    OUT.write_text(
        "/* GENERATED by scripts/build.py from content/products/*.json.\n"
        "   Don't edit this file: edit the pieces on the admin page (/admin). */\n"
        "window.PRODUCTS = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"products.js: {len(items)} pieces")


def make_thumbnails() -> None:
    try:
        from PIL import Image, ImageOps
    except ImportError:
        print("Pillow not installed; skipping thumbnails (the site falls back to full photos)")
        return
    made = 0
    for f in sorted(UPLOADS.iterdir()):
        if f.suffix.lower() not in {".webp", ".jpg", ".jpeg", ".png"} or f.stem.endswith("-sm"):
            continue
        sm = f.with_name(f.stem + "-sm.webp")
        if sm.exists() and sm.stat().st_mtime >= f.stat().st_mtime:
            continue
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            im.thumbnail((500, 625 * 2))
            im.save(sm, "WEBP", quality=78, method=6)
        made += 1
    print(f"thumbnails: {made} new")


if __name__ == "__main__":
    write_products(load_products())
    make_thumbnails()
